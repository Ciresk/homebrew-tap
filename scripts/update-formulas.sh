#!/usr/bin/env bash
# Regenerates Formula/ciresk.rb and Formula/ciresk-ci.rb from the checksums.txt of two releases on
# https://get.ciresk.com (the layout: Ciresk/ciresk-ci install/LAYOUT.md). Run after every release, commit, push:
#
#   scripts/update-formulas.sh v1.3.0 v1.0.3        # <ciresk tag> <ciresk-ci tag>
#
# CHECKSUMS_CIRESK / CHECKSUMS_CI may point at local checksums.txt files instead of the published ones.
# A platform whose archive is not in checksums.txt gets no url block (brew then refuses that platform
# until the formula is regenerated), and the script says which.
set -euo pipefail
CIRESK_TAG=${1:?usage: update-formulas.sh <ciresk tag> <ciresk-ci tag>}
CI_TAG=${2:?usage: update-formulas.sh <ciresk tag> <ciresk-ci tag>}
ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
BASE=https://get.ciresk.com

sums() { # <env override> <prefix> <tag>
  if [ -n "${!1:-}" ]; then cat "${!1}"; else curl -fsSL "$BASE/$2/$3/checksums.txt"; fi
}
sha_of() { # <checksums text> <file>
  printf '%s\n' "$1" | awk -v f="$2" '{ n=$2; sub(/^\*/, "", n); if (n == f) print $1 }'
}

# block <sums> <name> <prefix> <tag> <os> <arch> <indent>
block() {
  local file="$2-$4-$5-$6.tar.gz" sha
  sha=$(sha_of "$1" "$file")
  if [ -z "$sha" ]; then echo "warning: $file is not in $3/$4/checksums.txt; no $5/$6 block" >&2; return; fi
  printf '%s  url "%s/%s/%s/%s"\n%s  sha256 "%s"\n' "$7" "$BASE" "$3" "$4" "$file" "$7" "$sha"
}

# formula <class> <name> <prefix> <tag> <desc> <depends line or empty> <test line>
formula() {
  local class=$2 name=$3 prefix=$4 tag=$5 desc=$6 depends=$7 test=$8 s=$1
  {
    echo "# Generated by scripts/update-formulas.sh $CIRESK_TAG $CI_TAG; do not edit by hand."
    echo "class $class < Formula"
    echo "  desc \"$desc\""
    echo "  homepage \"https://ciresk.com\""
    echo "  version \"${tag#v}\""
    echo "  license :cannot_represent"
    echo
    echo "  on_macos do"
    echo "    on_arm do"; block "$s" "$name" "$prefix" "$tag" darwin aarch64 "    "; echo "    end"
    echo "    on_intel do"; block "$s" "$name" "$prefix" "$tag" darwin x86_64 "    "; echo "    end"
    echo "  end"
    echo
    echo "  on_linux do"
    echo "    on_arm do"; block "$s" "$name" "$prefix" "$tag" linux aarch64 "    "; echo "    end"
    echo "    on_intel do"; block "$s" "$name" "$prefix" "$tag" linux x86_64 "    "; echo "    end"
    echo "  end"
    [ -n "$depends" ] && { echo; echo "  $depends"; }
    echo
    echo "  def install"
    echo "    bin.install \"$name\""
    echo "  end"
    echo
    echo "  test do"
    echo "    $test"
    echo "  end"
    echo "end"
  }
}

mkdir -p "$ROOT/Formula"
S_CIRESK=$(sums CHECKSUMS_CIRESK ciresk "$CIRESK_TAG")
S_CI=$(sums CHECKSUMS_CI ci "$CI_TAG")
formula "$S_CIRESK" Ciresk ciresk ciresk "$CIRESK_TAG" \
  "Ciresk command line: the umbrella that product plugins (Ciresk CI) plug into" "" \
  "assert_match \"${CIRESK_TAG#v}\", shell_output(\"#{bin}/ciresk --version\")" > "$ROOT/Formula/ciresk.rb"
formula "$S_CI" CireskCi ciresk-ci ci "$CI_TAG" \
  "Ciresk CI: run checks, tests and builds for a repository on remote workers (ciresk ci ...)" \
  "depends_on \"ciresk/tap/ciresk\"" \
  "assert_match \"Ciresk CI\", shell_output(\"#{bin}/ciresk-ci --help\")" > "$ROOT/Formula/ciresk-ci.rb"
echo "wrote Formula/ciresk.rb ($CIRESK_TAG) and Formula/ciresk-ci.rb ($CI_TAG)"
